-- 迁移 v0.7.15：微信提醒「额度耗尽」标记
-- ============================================================
-- 背景：一次性订阅没有长期通道（长期订阅只对政务/医疗/交通/金融/教育类目开放，
--       本小程序类目「信息查询」申请不到），值日提醒一天两条（21:00 预告 + 07:00 当天）
--       意味着每人每天消耗 2 条额度。额度耗尽后发送静默失败（43101），
--       学生完全无感知 —— 必须有一个「失效」标记，前端据此把人拉回来重新授权。
--
-- 写入方：cron-weekly.remindDuty()
--   · 发送成功         → remind_block = 0
--   · 发送 43101（拒绝/额度用尽） → remind_block = 1
-- 读取方：duty.today → member.remindBlock（首页据此显示「微信提醒已失效，点此重新开启」）
-- 清除方：member.remindReopen（学生重新授权后自助调用）
--
-- ⚠️ TDSQL 不支持 `ADD COLUMN IF NOT EXISTS`（报 1064），已用普通 ALTER 在线上执行；
--    重复执行会报 1060「Duplicate column name」，属预期、可忽略。

ALTER TABLE member
  ADD COLUMN remind_block TINYINT NOT NULL DEFAULT 0
    COMMENT '1=微信提醒额度疑似耗尽（cron 发送 43101 时置 1，重新授权后清 0）';

-- 存量基线：上线前所有成员都视为「额度未知」，置 0 即可（首页不弹提示）。
-- 已开启提醒的同学会在下一次 cron 发送时被重新标记。
