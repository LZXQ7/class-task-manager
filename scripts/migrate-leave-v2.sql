-- ===================== 列语义（唯一口径，改代码前先看这里） =====================
-- start_time / end_time ：TIME，NULL = 整天请假（00:00–24:00 全算）。
-- ⚠️ 双口径（v1.0.8.77 / 2026-11-20 用户定稿，唯一权威语义）：
--   · **单日**（start_date = end_date）：非 NULL = 当天时段（如 08:00–18:00，periods am+pm
--     晚上回校）；「正在请假」= 当天 且 当前时刻 ∈ [start_time,end_time]。
--   · **跨天**（start_date < end_date）= **一条连续区间**，不是每天重复：
--       首日只卡下界（时刻 >= start_time）、末日只卡上界（时刻 <= end_time）、
--       中间整天（含晚上）连续。例 1/1–1/3 上午+下午 ⇒ 1/1 08:00 起、1/3 18:00 止。
--       跨天时 periods 不参与判定（首末边界只认 start_time/end_time）。
--       **只填一边时间（含两列都空）⇒ 整天假，两端都不卡**。
--   （旧语义「区间内每天的相同时段、不支持错位写法」已于 1.0.8.77 废止，勿再引用。）
