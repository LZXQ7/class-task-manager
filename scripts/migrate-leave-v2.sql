-- ===================== 列语义（唯一口径，改代码前先看这里） =====================
-- start_time / end_time ：TIME，NULL = 整天请假（00:00–24:00 全算）。
--                         非 NULL = **区间内每天**的相同时段（跨天也按每天这个时段，
--                         不支持「首日 14:00 才开始」这类错位写法）。
--                         跨天 + 时段的「正在请假」判定 = 当天 ∈ [start_date,end_date]
--                         且 当前时刻 ∈ [start_time,end_time]。
